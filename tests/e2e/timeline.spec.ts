import { openDetailed } from './helpers';
import { expect, test } from '@playwright/test';
test('work input editing preserves formal minutes without a timeline', async ({ page }) => {
  await openDetailed(page);
  const day = page.locator('.day').last();
  await day.locator('[data-field="start"]').fill('9');
  await day.locator('[data-field="end"]').fill('5p');
  await day.locator('[data-field="end"]').blur();
  await expect(page.locator('.timeline, [data-handle]')).toHaveCount(0);
  await expect(day.locator('.day-hours')).toHaveText('8:00');
  await day.locator('[data-field="start"]').fill('905');
  await day.locator('[data-field="start"]').blur();
  await expect(day.locator('.day-hours')).toHaveText('7:55');
});
test('blank dates retain independent editable break minutes', async ({ page }) => {
  await openDetailed(page);
  const day = page.locator('.day').first();
  await day.locator('[data-add-break]').click();
  await expect(day.locator('[data-duration-date]')).toHaveValue('30');
  await expect(page.locator('#daily-report .report-grand-total')).toContainText('0:00');
  await page.reload();
  await expect(page.locator('.day').first().locator('[data-duration-date]')).toHaveValue('30');
});
test('mobile time fields and break controls remain editable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await openDetailed(page);
  const day = page.locator('.day').last();
  await day.locator('[data-field="start"]').fill('855');
  await day.locator('[data-field="end"]').fill('5p');
  await day.locator('[data-field="end"]').blur();
  await day.locator('[data-add-break]').click();
  await day.locator('[data-duration-date]').fill('15');
  await day.locator('[data-duration-date]').blur();
  await expect(day.locator('.day-hours')).toHaveText('7:50');
  const switches = day.locator('.meridiem');
  const first = await switches.nth(0).boundingBox();
  const second = await switches.nth(1).boundingBox();
  expect(first!.x + first!.width).toBeLessThanOrEqual(second!.x + 1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
