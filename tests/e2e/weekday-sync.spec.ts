import { openDetailed } from "./helpers";
import { test, expect } from '@playwright/test';
test('weekday copies include PM and stay linked until manually changed', async ({page}) => {
  await openDetailed(page);
  const monday = page.locator('.day').first();
  const tuesday = page.locator('.day').nth(1);
  const wednesday = page.locator('.day').nth(2);
  await monday.locator('[data-field="start"]').fill('800');
  await monday.locator('[data-field="end"]').fill('430');
  await monday.locator('[data-field="end"]').blur();
  await monday.locator('[data-toggle-meridiem="end"]').click();
  await expect(tuesday.locator('[data-toggle-meridiem="end"]')).toHaveText('PM');
  await expect(page.locator('.day').nth(5).locator('[data-field="start"]')).toHaveValue('');
  await expect(page.locator('.day').nth(6).locator('[data-field="start"]')).toHaveValue('');
  await tuesday.locator('[data-field="end"]').fill('3p');
  await tuesday.locator('[data-field="end"]').blur();
  await monday.locator('[data-field="end"]').fill('5p');
  await monday.locator('[data-field="end"]').blur();
  await expect(tuesday.locator('[data-field="end"]')).toHaveValue('3:00');
  await expect(wednesday.locator('[data-field="end"]')).toHaveValue('5:00');
  await page.reload();
  await monday.locator('[data-field="end"]').fill('6p');
  await monday.locator('[data-field="end"]').blur();
  await expect(tuesday.locator('[data-field="end"]')).toHaveValue('3:00');
  await expect(wednesday.locator('[data-field="end"]')).toHaveValue('6:00');
  const start = monday.locator('[data-field="start"]');
  await start.click();
  await start.blur();
  await expect(start).toHaveValue('8:00');
  await start.click();
  await page.keyboard.type('900');
  await start.blur();
  await expect(start).toHaveValue('9:00');
  await expect(wednesday.locator('[data-field="start"]')).toHaveValue('9:00');
});
